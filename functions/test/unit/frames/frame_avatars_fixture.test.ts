import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { format, resolveConfig } from 'prettier';
import { describe, expect, it } from 'vitest';

import { type FrameDaySources, assembleFrameDay } from '../../../src/frames/frame_day';

/**
 * The golden fixture three codebases read (C-0023 rev 18, rev 19): what the
 * server's own day assembly sends the wall for a set of looks. The frame
 * parses the same file (`FrameAvatarFixtureTest.kt`, from its copy in
 * `../NestPrep-Home/app/src/test/resources/`) and the app resolves the same
 * looks (`app/test/features/avatars/model/frame_avatars_fixture_test.dart`).
 *
 * After a deliberate change to the contract, write both copies again with
 * `UPDATE_FIXTURES=1 npx vitest run test/unit/frames/frame_avatars_fixture.test.ts`.
 */

const FIXTURE = resolve(__dirname, '../../fixtures/frame_avatars.json');
const FRAME_RESOURCES = resolve(__dirname, '../../../../../NestPrep-Home/app/src/test/resources');
const FRAME_COPY = resolve(FRAME_RESOURCES, 'frame_avatars.json');

const TODAY = '2026-08-11';
const TIME_ZONE = 'Africa/Johannesburg';
const HASH = '0123456789abcdef0123456789abcdef';

interface Sitter {
  readonly name: string;
  readonly color: string;
  readonly kid?: true;
  readonly birthday?: string;
  /** False where the phone is deliberately more forgiving than the server. */
  readonly phoneAgrees?: false;
  readonly look?: unknown;
}

const look = (
  base: string | null,
  stage: number,
  wear: Record<string, string> = {},
): Record<string, unknown> => ({
  v: 1,
  base,
  stage,
  wear,
});

const SITTERS: readonly Sitter[] = [
  { name: 'Ada', color: 'coral', kid: true, look: look('preset:pip', 0) },
  { name: 'Ben', color: 'teal', kid: true, look: look('preset:pip', 1) },
  { name: 'Cal', color: 'violet', kid: true, look: look('preset:pip', 2) },
  {
    name: 'Dee',
    color: 'amber',
    look: look('preset:olive', 3, {
      top: 'acc-crown',
      badge: 'acc-star',
      ring: 'acc-rainbow-ring',
      face: 'acc-round-glasses',
    }),
  },
  {
    name: 'Eli',
    color: 'teal',
    look: look(`image:${HASH}`, 3, { badge: 'acc-star', face: 'acc-round-glasses' }),
  },
  {
    name: 'Fay',
    color: 'coral',
    look: look(null, 3, { top: 'acc-crown', face: 'acc-round-glasses' }),
  },
  {
    name: 'Gus',
    color: 'violet',
    kid: true,
    birthday: '2018-08-11',
    look: look('preset:pip', 2, { top: 'acc-crown', badge: 'acc-star' }),
  },
  {
    name: 'Hal',
    color: 'teal',
    look: look('preset:pip', 3, { top: 'acc-jetpack', badge: 'acc-crown' }),
  },
  { name: 'Ivy', color: 'coral', phoneAgrees: false, look: { ...look('preset:pip', 2), v: 2 } },
  { name: 'Jo', color: 'amber', birthday: '--08-11' },
  { name: 'Kit', color: 'violet', look: look(null, 3) },
  { name: 'Lou', color: 'teal', phoneAgrees: false, look: look('preset:godzilla', 1) },
];

function sources(): FrameDaySources {
  const ids = SITTERS.map((sitter) => [`m-${sitter.name.toLowerCase()}`, sitter] as const);
  const pick = <T>(of: (sitter: Sitter) => T | undefined): Record<string, T> =>
    Object.fromEntries(
      ids.flatMap(([id, sitter]) => {
        const value = of(sitter);
        return value === undefined ? [] : [[id, value] as const];
      }),
    );
  return {
    householdName: 'The Oak Street Nest',
    frameName: 'Kitchen',
    panels: {
      calendar: false,
      todos: false,
      meals: false,
      lunch: false,
      addEvents: false,
      share: false,
      people: false,
      helperMemberId: null,
    },
    screensaver: null,
    today: TODAY,
    localMinute: 9 * 60,
    names: pick((sitter) => sitter.name),
    colors: pick((sitter) => sitter.color),
    kids: ids.filter(([, sitter]) => sitter.kid === true).map(([id]) => id),
    looks: pick((sitter) => sitter.look),
    birthdays: pick((sitter) => sitter.birthday),
    timeZone: TIME_ZONE,
  };
}

async function built(): Promise<string> {
  const day = assembleFrameDay(sources());
  const fixture = {
    about:
      'Generated by functions/test/unit/frames/frame_avatars_fixture.test.ts from the real day assembly; never edit by hand.',
    today: TODAY,
    timeZone: TIME_ZONE,
    members: SITTERS.map((sitter) => ({
      name: sitter.name,
      birthday: sitter.birthday ?? null,
      phoneAgrees: sitter.phoneAgrees ?? true,
      ...(sitter.look === undefined ? {} : { look: sitter.look }),
    })),
    day: { household: day.household },
  };
  return format(JSON.stringify(fixture), {
    ...(await resolveConfig(FIXTURE)),
    parser: 'json',
  });
}

describe('the frame avatars fixture', () => {
  it('is what the day assembly sends today', async () => {
    const now = await built();
    if (process.env.UPDATE_FIXTURES === '1') {
      writeFileSync(FIXTURE, now);
      if (existsSync(FRAME_RESOURCES)) writeFileSync(FRAME_COPY, now);
    }
    expect(readFileSync(FIXTURE, 'utf8')).toBe(now);
  });

  it.skipIf(!existsSync(FRAME_RESOURCES))('is the file the frame’s tests parse', () => {
    expect(readFileSync(FRAME_COPY, 'utf8')).toBe(readFileSync(FIXTURE, 'utf8'));
  });

  it('covers every base, every slot, a birthday, a malformed piece and no look', async () => {
    const { day } = JSON.parse(await built()) as {
      day: { household: { members: { name: string; avatar?: unknown }[] } };
    };
    const sent = Object.fromEntries(
      day.household.members.map((member) => [member.name, member.avatar]),
    );
    expect(sent).toMatchObject({
      Ada: { base: { preset: 'nestling-pip-0' }, layers: [] },
      Ben: { base: { preset: 'nestling-pip-1' } },
      Cal: { base: { preset: 'nestling-pip-2' } },
      Dee: {
        base: { preset: 'nestling-olive-3' },
        layers: [
          { slot: 'top', id: 'acc-crown' },
          { slot: 'badge', id: 'acc-star' },
          { slot: 'ring', id: 'acc-rainbow-ring' },
          { slot: 'face', id: 'acc-round-glasses' },
        ],
      },
      Eli: { base: { image: HASH }, layers: [{ slot: 'badge', id: 'acc-star' }] },
      Fay: { base: { initial: true }, layers: [{ slot: 'top', id: 'acc-crown' }] },
      Gus: {
        base: { preset: 'nestling-pip-2' },
        layers: [
          { slot: 'top', id: 'moment-birthday-hat' },
          { slot: 'badge', id: 'acc-star' },
        ],
      },
      Hal: { base: { preset: 'nestling-pip-3' }, layers: [] },
      Kit: { base: { initial: true }, layers: [] },
    });
    expect(sent.Ivy).toBeUndefined();
    expect(sent.Jo).toBeUndefined();
    expect(sent.Lou).toBeUndefined();
    expect(JSON.stringify(day)).not.toContain('m-');
  });
});
