import json
import pathlib
import shutil
import subprocess

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent
WORK = HERE / "work"
DART = REPO / "app/lib/features/avatars/model/avatar_catalogue.g.dart"
TS = REPO / "functions/src/avatars/avatar_catalogue.ts"
KOTLIN = REPO.parent / "NestPrep-Home/app/src/main/java/io/nullstate/nestprep/home/AvatarFaces.kt"
TARGETS = [
    (REPO / "app/assets/avatars", 384),
    (REPO / "functions/assets/avatars", 384),
    (REPO.parent / "NestPrep-Home/app/src/main/assets/avatars", 128),
]
STAGES = range(4)
BUDDY_KINDS = ["creature", "colour", "loves", "wears", "power"]
HEADER = "Generated by tools/avatar-pictures/build.py from catalogue.json. Do not edit."


def assets(catalogue: dict) -> list[tuple[str, str]]:
    pairs = []
    for nestling in catalogue["nestlings"]:
        pairs += [(f"nestling-{nestling['name']}-{stage}",) * 2 for stage in STAGES]
    pairs += [(f"acc-{a['id']}",) * 2 for a in catalogue["accessories"]]
    pairs += [(f"moment-{m['id']}", f"moment-{m.get('art', m['id'])}") for m in catalogue["moments"]]
    return pairs


def ship(catalogue: dict) -> tuple[int, list[str]]:
    shipped, missing = 0, []
    for directory, _ in TARGETS:
        if directory.exists():
            shutil.rmtree(directory)
        directory.mkdir(parents=True)
    for asset_id, picture in assets(catalogue):
        sources = [WORK / str(size) / f"{picture}.webp" for _, size in TARGETS]
        if not all(s.exists() for s in sources):
            missing.append(asset_id)
            continue
        for (directory, _), source in zip(TARGETS, sources):
            shutil.copy(source, directory / f"{asset_id}.webp")
        shipped += 1
    return shipped, missing


def faces(catalogue: dict) -> list[tuple[str, dict]]:
    return [
        (f"nestling-{nestling['name']}-{stage}", face)
        for nestling in catalogue["nestlings"]
        for stage, face in zip(STAGES, nestling.get("faces", []))
        if face
    ]


def quoted(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def ts_rule(rule: dict) -> str:
    if rule["kind"] == "birthday":
        return "{ kind: 'birthday' }"
    if rule["kind"] == "easter":
        return f"{{ kind: 'easter', from: {rule['from']}, to: {rule['to']} }}"
    hemisphere = f", hemisphere: {quoted(rule['hemisphere'])}" if "hemisphere" in rule else ""
    return f"{{ kind: 'dates', from: {quoted(rule['from'])}, to: {quoted(rule['to'])}{hemisphere} }}"


def dart_rule(rule: dict) -> str:
    if rule["kind"] == "birthday":
        return "BirthdayMomentRule()"
    if rule["kind"] == "easter":
        return f"EasterMomentRule(from: {rule['from']}, to: {rule['to']})"
    hemisphere = f", hemisphere: AvatarHemisphere.{rule['hemisphere']}" if "hemisphere" in rule else ""
    return f"DatesMomentRule(from: {quoted(rule['from'])}, to: {quoted(rule['to'])}{hemisphere})"


def typescript(catalogue: dict) -> str:
    lines = [
        f"// {HEADER}",
        "",
        "export type AvatarSlot = 'top' | 'badge' | 'ring' | 'face';",
        "",
        "export type MomentRule =",
        "  | { kind: 'birthday' }",
        "  | { kind: 'dates'; from: string; to: string; hemisphere?: 'south' | 'north' }",
        "  | { kind: 'easter'; from: number; to: number };",
        "",
        "export type BuddyKind = 'creature' | 'colour' | 'loves' | 'wears' | 'power';",
        "",
        "export const NESTLING_STAGES = [0, 1, 2, 3] as const;",
        "",
        "export const NESTLINGS: readonly { name: string; label: string }[] = [",
    ]
    lines += [f"  {{ name: {quoted(n['name'])}, label: {quoted(n['label'])} }}," for n in catalogue["nestlings"]]
    lines += ["];", "", "export const ACCESSORIES: readonly { id: string; label: string; slot: AvatarSlot; stars: number }[] = ["]
    lines += [
        f"  {{ id: {quoted('acc-' + a['id'])}, label: {quoted(a['label'])}, slot: {quoted(a['slot'])}, stars: {a['stars']} }},"
        for a in catalogue["accessories"]
    ]
    lines += ["];", "", "export const MOMENTS: readonly { id: string; label: string; slot: AvatarSlot; rule: MomentRule }[] = ["]
    lines += [
        f"  {{ id: {quoted('moment-' + m['id'])}, label: {quoted(m['label'])}, slot: {quoted(m['slot'])}, rule: {ts_rule(m['rule'])} }},"
        for m in catalogue["moments"]
    ]
    lines += ["];", "", "export const BUDDY: Readonly<Record<BuddyKind, readonly { id: string; label: string }[]>> = {"]
    for kind in BUDDY_KINDS:
        lines.append(f"  {kind}: [")
        lines += [f"    {{ id: {quoted(w['id'])}, label: {quoted(w['label'])} }}," for w in catalogue["buddy"][kind]]
        lines.append("  ],")
    lines += ["};", "", "export const NESTLING_FACES: Readonly<Record<string, { x: number; y: number; w: number }>> = {"]
    lines += [f"  {quoted(asset_id)}: {{ x: {f['x']}, y: {f['y']}, w: {f['w']} }}," for asset_id, f in faces(catalogue)]
    lines += [
        "};",
        "",
        "export function nestlingAssetId(name: string, stage: number): string {",
        "  return `nestling-${name}-${String(stage)}`;",
        "}",
        "",
    ]
    return "\n".join(lines)


def dart(catalogue: dict) -> str:
    lines = [
        "// GENERATED CODE - DO NOT MODIFY BY HAND",
        f"// {HEADER}",
        "",
        "enum AvatarSlot { top, badge, ring, face }",
        "",
        "enum AvatarHemisphere { south, north }",
        "",
        "enum AvatarBuddyKind { creature, colour, loves, wears, power }",
        "",
        "const avatarNestlingStages = [0, 1, 2, 3];",
        "",
        "class AvatarNestling {",
        "  const AvatarNestling({required this.name, required this.label});",
        "  final String name;",
        "  final String label;",
        "}",
        "",
        "class AvatarAccessory {",
        "  const AvatarAccessory({required this.id, required this.label, required this.slot, required this.stars});",
        "  final String id;",
        "  final String label;",
        "  final AvatarSlot slot;",
        "  final int stars;",
        "}",
        "",
        "class AvatarMoment {",
        "  const AvatarMoment({required this.id, required this.label, required this.slot, required this.rule});",
        "  final String id;",
        "  final String label;",
        "  final AvatarSlot slot;",
        "  final MomentRule rule;",
        "}",
        "",
        "class AvatarChoiceWord {",
        "  const AvatarChoiceWord({required this.id, required this.label});",
        "  final String id;",
        "  final String label;",
        "}",
        "",
        "class AvatarFace {",
        "  const AvatarFace({required this.x, required this.y, required this.w});",
        "  final double x;",
        "  final double y;",
        "  final double w;",
        "}",
        "",
        "sealed class MomentRule {",
        "  const MomentRule();",
        "}",
        "",
        "class BirthdayMomentRule extends MomentRule {",
        "  const BirthdayMomentRule();",
        "}",
        "",
        "class DatesMomentRule extends MomentRule {",
        "  const DatesMomentRule({required this.from, required this.to, this.hemisphere});",
        "  final String from;",
        "  final String to;",
        "  final AvatarHemisphere? hemisphere;",
        "}",
        "",
        "class EasterMomentRule extends MomentRule {",
        "  const EasterMomentRule({required this.from, required this.to});",
        "  final int from;",
        "  final int to;",
        "}",
        "",
        "String nestlingAssetId(String name, int stage) => 'nestling-$name-$stage';",
        "",
        "String avatarAssetPath(String assetId) => 'assets/avatars/$assetId.webp';",
        "",
        "const avatarNestlings = <AvatarNestling>[",
    ]
    lines += [f"  AvatarNestling(name: {quoted(n['name'])}, label: {quoted(n['label'])})," for n in catalogue["nestlings"]]
    lines += ["];", "", "const avatarAccessories = <AvatarAccessory>["]
    lines += [
        f"  AvatarAccessory(id: {quoted('acc-' + a['id'])}, label: {quoted(a['label'])}, slot: AvatarSlot.{a['slot']}, stars: {a['stars']}),"
        for a in catalogue["accessories"]
    ]
    lines += ["];", "", "const avatarMoments = <AvatarMoment>["]
    lines += [
        f"  AvatarMoment(id: {quoted('moment-' + m['id'])}, label: {quoted(m['label'])}, slot: AvatarSlot.{m['slot']}, rule: {dart_rule(m['rule'])}),"
        for m in catalogue["moments"]
    ]
    lines += ["];", "", "const avatarBuddy = <AvatarBuddyKind, List<AvatarChoiceWord>>{"]
    for kind in BUDDY_KINDS:
        lines.append(f"  AvatarBuddyKind.{kind}: [")
        lines += [f"    AvatarChoiceWord(id: {quoted(w['id'])}, label: {quoted(w['label'])})," for w in catalogue["buddy"][kind]]
        lines.append("  ],")
    lines += ["};", "", "const avatarNestlingFaces = <String, AvatarFace>{"]
    lines += [f"  {quoted(asset_id)}: AvatarFace(x: {f['x']}, y: {f['y']}, w: {f['w']})," for asset_id, f in faces(catalogue)]
    lines += ["};", ""]
    return "\n".join(lines)


def kotlin(catalogue: dict) -> str:
    lines = [
        f"// {HEADER}",
        "",
        "package io.nullstate.nestprep.home",
        "",
        "object AvatarFaces {",
        "",
        "    class Face(val x: Float, val y: Float, val w: Float)",
        "",
        "    fun of(assetId: String): Face? = FACES[assetId]",
        "",
        "    private val FACES: Map<String, Face> = hashMapOf(",
    ]
    lines += [f'        "{asset_id}" to Face({f["x"]}f, {f["y"]}f, {f["w"]}f),' for asset_id, f in faces(catalogue)]
    lines += ["    )", "}", ""]
    return "\n".join(lines)


def main() -> None:
    catalogue = json.loads((HERE / "catalogue.json").read_text())
    shipped, missing = ship(catalogue)
    DART.parent.mkdir(parents=True, exist_ok=True)
    TS.parent.mkdir(parents=True, exist_ok=True)
    DART.write_text(dart(catalogue))
    TS.write_text(typescript(catalogue))
    if KOTLIN.parent.exists():
        KOTLIN.write_text(kotlin(catalogue))
    subprocess.run([str(pathlib.Path.home() / "development/flutter/bin/dart"), "format", str(DART)], check=True, capture_output=True)
    subprocess.run([str(REPO / "functions/node_modules/.bin/prettier"), "--write", str(TS)], check=True, capture_output=True, cwd=REPO / "functions")
    print(json.dumps({"shipped": shipped, "total": shipped + len(missing), "missing": missing}))


if __name__ == "__main__":
    main()
