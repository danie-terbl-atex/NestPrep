import argparse
import json
import pathlib
import shutil
import subprocess

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent
APP_ASSETS = REPO / "app/assets/chore_pictures"
DART = REPO / "app/lib/features/todos/model/chore_picture_catalogue.dart"
FRAME_ASSETS = REPO.parent / "NestPrep-Home/app/src/main/assets/chore-pictures"


def dart_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--work", default=str(HERE / "work"))
    args = parser.parse_args()
    work = pathlib.Path(args.work)
    entries = json.loads((HERE / "catalogue.json").read_text())
    shipped = [e for e in entries if (work / "384" / f"{e['id']}.webp").exists() and (work / "192" / f"{e['id']}.webp").exists()]
    missing = [e["id"] for e in entries if e not in shipped]

    for directory in (APP_ASSETS, FRAME_ASSETS):
        if directory.exists():
            shutil.rmtree(directory)
        directory.mkdir(parents=True)
    for entry in shipped:
        shutil.copy(work / "384" / f"{entry['id']}.webp", APP_ASSETS / f"{entry['id']}.webp")
        shutil.copy(work / "192" / f"{entry['id']}.webp", FRAME_ASSETS / f"{entry['id']}.webp")

    lines = [
        "// Generated by tools/chore-pictures/build.py from catalogue.json. Do not edit.",
        "",
        "import 'chore_picture.dart';",
        "",
        "const chorePictureCatalogue = <ChorePicture>[",
    ]
    for entry in shipped:
        keywords = ", ".join(dart_string(k) for k in entry["keywords"])
        lines += [
            "  ChorePicture(",
            f"    id: {dart_string(entry['id'])},",
            f"    label: {dart_string(entry['label'])},",
            f"    category: ChorePictureCategory.{entry['category']},",
            f"    keywords: [{keywords}],",
            "  ),",
        ]
    lines += ["];", ""]
    DART.write_text("\n".join(lines))
    subprocess.run([str(pathlib.Path.home() / "development/flutter/bin/dart"), "format", str(DART)], check=True, capture_output=True)
    print(json.dumps({"shipped": len(shipped), "missing": missing}))


if __name__ == "__main__":
    main()
